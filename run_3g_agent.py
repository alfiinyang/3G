"""Run Script and Demonstration for 3G-agent.

This script demonstrates:
1. Client Parameter Collection (separate step)
2. Model and Client Initialization (separate step)
3. Skill Loading from a folder (e.g. ./skills/pedagogy-engineering)
4. Setting remote environment & securely persisting Environment IDs
5. Local file accessibility: saving files generated by the agent locally.
"""

import os
import sys
from pathlib import Path

# Add project root to sys.path
sys.path.insert(0, str(Path(__file__).parent.resolve()))

from three_g_agent import (
    ThreeGAgent,
    ThreeGAgentConfig,
    ClientParameterCollector,
    ModelInitializer,
    EnvironmentStore,
    SkillLoader,
    FileStorageManager,
)


# Ensure stdout handles UTF-8 on Windows
if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

def run_demonstration():
    print("=" * 70)
    print("  3G-agent: Custom Reusable Antigravity Agent Demo")
    print("=" * 70)

    # -------------------------------------------------------------
    # 1. PARAMETER COLLECTION (Separated from initialization & execution)
    # -------------------------------------------------------------
    skills_folder = Path("./skills/pedagogy-engineering")
    if not skills_folder.exists():
        skills_folder = Path("./skills")

    print(f"\n[Step 1] Collecting Client Parameters...")
    config = ThreeGAgentConfig(
        agent_name="3G-agent",
        model_name="antigravity-preview-09-2026",
        environment_type="remote",  # Mandatory requirement
        skills_dir=skills_folder,
        instructions_file=Path("./instructions.md"),
        state_dir="./.3g_agent",
        output_dir="./outputs/3g_agent",
    )
    ClientParameterCollector.validate(config)
    print(f"  [+] Agent Name       : {config.agent_name}")
    print(f"  [+] Environment Type : {config.environment_type} (Google-managed sandbox)")
    print(f"  [+] Target Model     : {config.model_name}")
    print(f"  [+] Instructions File: {config.instructions_file.resolve()} ({'ready' if config.instructions_file.exists() else 'not found'})")
    print(f"  [+] Skills Folder    : {config.skills_dir.resolve()}")
    print(f"  [+] State Directory  : {config.state_dir.resolve()} (secure environment ID store)")
    print(f"  [+] Output Directory : {config.output_dir.resolve()} (local file accessibility)")

    # -------------------------------------------------------------
    # 2. MODEL INITIALIZATION (Separated from execution)
    # -------------------------------------------------------------
    print(f"\n[Step 2] Initializing Client Connection...")
    initialized_client = ModelInitializer.initialize(config)
    print(f"  [+] Initialized client backend: {initialized_client.backend_type}")

    # -------------------------------------------------------------
    # 3. SKILL DISCOVERY AND PARSING
    # -------------------------------------------------------------
    print(f"\n[Step 3] Loading Skills from Folder...")
    skill_loader = SkillLoader(config.skills_dir)
    print(f"  [+] Found {len(skill_loader.skills)} skill package(s):")
    for s in skill_loader.skills:
        print(f"    - [{s.name}] - {s.description[:75]}...")
        print(f"      |-- Contains {len(s.auxiliary_files)} stages & resource files.")

    # -------------------------------------------------------------
    # 4. ENVIRONMENT STORE (Secure Environment ID Management)
    # -------------------------------------------------------------
    print(f"\n[Step 4] Checking Remote Environment ID Store...")
    env_store = EnvironmentStore(state_dir=config.state_dir, agent_name=config.agent_name)
    current_env_id = env_store.get_environment_id()
    if current_env_id:
        print(f"  [+] Found active persistent Environment ID: {current_env_id}")
    else:
        print(f"  [+] No environment ID saved yet. A new remote sandbox container will be created on first turn.")

    # -------------------------------------------------------------
    # 5. LOCAL FILE ACCESSIBILITY (Storage Manager)
    # -------------------------------------------------------------
    print(f"\n[Step 5] Initializing Local File Storage Manager...")
    storage_manager = FileStorageManager(output_dir=config.output_dir)
    print(f"  [+] Local deliverables will be indexed at: {storage_manager.manifest_file.resolve()}")

    # -------------------------------------------------------------
    # 6. ASSEMBLE 3G-AGENT (Execution Engine)
    # -------------------------------------------------------------
    print(f"\n[Step 6] Assembling Reusable 3G-agent...")
    agent = ThreeGAgent(
        config=config,
        initialized_client=initialized_client,
        skill_loader=skill_loader,
        environment_store=env_store,
        storage_manager=storage_manager,
    )
    print("  [+] 3G-agent ready for operation!")

    # -------------------------------------------------------------
    # 7. DEMONSTRATE EXECUTION & FILE SAVING
    # -------------------------------------------------------------
    print("\n" + "=" * 70)
    print("  Demonstrating Local Deliverable Creation & Accessibility")
    print("=" * 70)

    # Let's save a sample initial specification locally to demonstrate file accessibility
    sample_deliverable = """# Pedagogy Engineering Specification: Initial Blueprint
## Generated by 3G-agent (Antigravity SDK)

### Environment Details:
- Type: Remote Sandbox
- Persisted Environment ID: env_sample_3g_persisted_state
- Agent: 3G-agent

### Summary:
Audience: Flour Mills of Nigeria PLC technical operators
Domain: Industrial Milling & Process Automation
Pedagogical Architecture: 21 Autonomous Stages configured from skills/pedagogy-engineering.
"""
    saved = storage_manager.save_file("sample_pedagogy_spec.md", sample_deliverable)
    print(f"\nSuccessfully stored deliverable locally:")
    print(f"  - Filename   : {saved.file_name}")
    print(f"  - Local Path : {saved.local_path}")
    print(f"  - File URI   : {saved.file_uri}")
    print(f"  - SHA256     : {saved.sha256[:16]}...")
    print(f"  - Size       : {saved.size_bytes} bytes")

    # Save a test environment ID to demonstrate persistence
    if not current_env_id:
        env_store.save_environment_id(
            "env_3g_agent_session_demo",
            skills_signature=skill_loader.get_combined_signature(),
            metadata={"description": "Demo environment session initialized"},
        )
        print(f"\n[+] Securely saved demo remote Environment ID: {env_store.get_environment_id()}")

    print("\n" + "=" * 70)
    print("  3G-agent Setup and Architecture Validation Complete! [OK]")
    print("=" * 70)


if __name__ == "__main__":
    run_demonstration()
