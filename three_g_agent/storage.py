"""Local File Accessibility and Artifact Persistence for 3G-agent.

Requirement:
"ensure to provide file accessibility after creation by agent (i.e. store file locally)."

This module guarantees that any files, code outputs, pedagogical specifications,
or deliverables generated by 3G-agent inside the remote environment or output
streams are downloaded, saved, and indexed locally on the user's filesystem.
"""

from __future__ import annotations

import hashlib
import json
import logging
import os
import re
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

logger = logging.getLogger("3G-agent.storage")


@dataclass
class SavedFile:
    """Represents a file created by 3G-agent and stored locally."""
    file_name: str
    local_path: Path
    file_uri: str
    size_bytes: int
    sha256: str
    created_at: str
    source_type: str  # "interaction_file", "extracted_block", "direct"

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["local_path"] = str(self.local_path.resolve())
        return data


class FileStorageManager:
    """Manages local storage and file accessibility for 3G-agent deliverables."""

    def __init__(self, output_dir: Path | str = "./outputs/3g_agent") -> None:
        self.output_dir = Path(output_dir)
        self.manifest_file = self.output_dir / "manifest.json"
        self._ensure_output_dir()

    def _ensure_output_dir(self) -> None:
        """Ensures the local output directory exists."""
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def _file_to_uri(self, path: Path) -> str:
        """Converts local Path to a clickable file:// URI format."""
        return path.resolve().as_uri()

    def save_file(
        self,
        relative_name: str,
        content: Union[str, bytes],
        source_type: str = "direct",
    ) -> SavedFile:
        """Saves content to a local file in output_dir and registers it in the manifest.
        
        Args:
            relative_name: Target relative filename or subpath (e.g., "stage_1_output.md").
            content: Text string or binary bytes to write.
            source_type: Origin indicator.
            
        Returns:
            SavedFile metadata record.
        """
        self._ensure_output_dir()
        target_path = self.output_dir / relative_name
        target_path.parent.mkdir(parents=True, exist_ok=True)

        if isinstance(content, str):
            target_path.write_text(content, encoding="utf-8")
            raw_bytes = content.encode("utf-8")
        else:
            target_path.write_bytes(content)
            raw_bytes = content

        size_bytes = len(raw_bytes)
        sha256 = hashlib.sha256(raw_bytes).hexdigest()
        created_at = datetime.now(timezone.utc).isoformat()
        file_uri = self._file_to_uri(target_path)

        record = SavedFile(
            file_name=relative_name,
            local_path=target_path,
            file_uri=file_uri,
            size_bytes=size_bytes,
            sha256=sha256,
            created_at=created_at,
            source_type=source_type,
        )

        self._update_manifest(record)
        logger.info("Saved local file: %s (%d bytes) -> %s", relative_name, size_bytes, file_uri)
        return record

    @staticmethod
    def _parse_opening_fence(line: str) -> Optional[tuple[int, str]]:
        """Detects if a line opens a code fence specifying a file deliverable.
        
        Supports:
          - ````markdown:pedagogical_plan.md
          - ```path/to/file.ext
          - ````python [sim.py]
          - ````python filename="sim.py" or file="sim.py"
          
        Returns (fence_length, clean_filename) or None.
        """
        stripped = line.strip()
        if not stripped.startswith("```"):
            return None

        m_fence = re.match(r"^(`{3,})", stripped)
        if not m_fence:
            return None
        fence_len = len(m_fence.group(1))
        rest = stripped[fence_len:].strip()
        if not rest:
            return None

        # Pattern A: lang:filename.ext or :filename.ext
        m_colon = re.match(r"^(?:[a-zA-Z0-9_\-]+)?:\s*([a-zA-Z0-9_\-\.\/\\]+\.[a-zA-Z0-9]+)\s*$", rest)
        if m_colon:
            return fence_len, Path(m_colon.group(1)).name

        # Pattern B: direct filename.ext
        m_direct = re.match(r"^([a-zA-Z0-9_\-\.\/\\]+\.[a-zA-Z0-9]{1,8})\s*$", rest)
        if m_direct and not m_direct.group(1).startswith(("python3.", "py3.")):
            return fence_len, Path(m_direct.group(1)).name

        # Pattern C: lang [filename.ext] or [filename.ext]
        m_bracket = re.match(r"^(?:[a-zA-Z0-9_\-]+)?\s*\[([a-zA-Z0-9_\-\.\/\\]+\.[a-zA-Z0-9]+)\]\s*$", rest)
        if m_bracket:
            return fence_len, Path(m_bracket.group(1)).name

        # Pattern D: lang filename="file.ext" or file="file.ext" or name="file.ext"
        m_named = re.match(r"^(?:[a-zA-Z0-9_\-]+)?\s*(?:filename|file|name)=[\"']([a-zA-Z0-9_\-\.\/\\]+\.[a-zA-Z0-9]+)[\"']\s*$", rest)
        if m_named:
            return fence_len, Path(m_named.group(1)).name

        return None

    def extract_and_save_deliverables(self, output_text: str) -> List[SavedFile]:
        """Extracts marked code blocks or deliverable files from the agent's output text.
        
        Properly handles nested code blocks inside markdown files (e.g. mermaid diagrams,
        code snippets, ASCII diagrams) without premature truncation.
        """
        saved: List[SavedFile] = []
        saved_names: set[str] = set()

        # Pattern 1: Explicit deliverable marker <!-- FILE: filename.ext --> content <!-- END FILE -->
        marker_pattern = re.compile(
            r"<!--\s*(?:FILE|DELIVERABLE):\s*([a-zA-Z0-9_\-\.\/\\]+\.[a-zA-Z0-9]+)\s*-->\s*\n?(.*?)<!--\s*END (?:FILE|DELIVERABLE)\s*-->",
            re.DOTALL | re.IGNORECASE,
        )
        for match in marker_pattern.finditer(output_text):
            filename, file_content = match.groups()
            clean_filename = Path(filename).name
            if clean_filename and clean_filename not in saved_names:
                record = self.save_file(
                    relative_name=clean_filename,
                    content=file_content.strip(),
                    source_type="extracted_marker",
                )
                saved.append(record)
                saved_names.add(clean_filename)

        # Pattern 2: Sequential fence scanner with nested block tracking
        lines = output_text.splitlines()
        i = 0
        num_lines = len(lines)

        while i < num_lines:
            line = lines[i]
            fence_info = self._parse_opening_fence(line)
            if fence_info:
                fence_len, clean_filename = fence_info
                if clean_filename in saved_names:
                    i += 1
                    continue

                is_markdown = clean_filename.lower().endswith((".md", ".markdown", ".mdown", ".mkd", ".txt"))
                block_lines: List[str] = []
                inner_depth = 0
                i += 1

                while i < num_lines:
                    curr_line = lines[i]

                    # If outer fence opened with 4+ backticks:
                    if fence_len >= 4:
                        if re.match(rf"^\s*`{{{fence_len},}}\s*$", curr_line):
                            i += 1
                            break
                        # If a new deliverable starts with >= fence_len backticks:
                        elif self._parse_opening_fence(curr_line):
                            m_new = re.match(r"^\s*(`{3,})", curr_line)
                            if m_new and len(m_new.group(1)) >= fence_len:
                                break
                        block_lines.append(curr_line)
                        i += 1
                    else:
                        # 3-backtick outer fence
                        if is_markdown:
                            new_file_info = self._parse_opening_fence(curr_line)
                            if new_file_info:
                                # A new deliverable block begins
                                break

                            # Inner code block open (e.g. ```mermaid, ```python)
                            is_inner_open = bool(re.match(r"^\s*`{3,}[a-zA-Z0-9_\-]+\s*$", curr_line))
                            is_bare_fence = bool(re.match(r"^\s*`{3,}\s*$", curr_line))

                            if is_inner_open:
                                inner_depth += 1
                                block_lines.append(curr_line)
                                i += 1
                            elif is_bare_fence:
                                if inner_depth > 0:
                                    inner_depth -= 1
                                    block_lines.append(curr_line)
                                    i += 1
                                else:
                                    # Outer closing fence
                                    i += 1
                                    break
                            else:
                                block_lines.append(curr_line)
                                i += 1
                        else:
                            # Non-markdown: first bare fence of at least fence_len closes it
                            if re.match(rf"^\s*`{{{fence_len},}}\s*$", curr_line):
                                i += 1
                                break
                            block_lines.append(curr_line)
                            i += 1

                content = "\n".join(block_lines)
                if content.strip():
                    record = self.save_file(
                        relative_name=clean_filename,
                        content=content,
                        source_type="extracted_block",
                    )
                    saved.append(record)
                    saved_names.add(clean_filename)
            else:
                i += 1

        return saved

    def capture_remote_interaction_files(
        self,
        interaction: Any,
        output_text: Optional[str] = None,
    ) -> List[SavedFile]:
        """Downloads and stores locally any files returned by the remote sandbox interaction."""
        saved_files: List[SavedFile] = []

        # 1. Check for interaction.files collection
        files_collection = getattr(interaction, "files", None)
        if files_collection:
            for item in files_collection:
                try:
                    file_name = getattr(item, "name", None) or f"artifact_{len(saved_files)}.bin"
                    local_target = self.output_dir / file_name
                    
                    if hasattr(item, "download"):
                        item.download(str(local_target))
                        saved_files.append(
                            SavedFile(
                                file_name=file_name,
                                local_path=local_target,
                                file_uri=self._file_to_uri(local_target),
                                size_bytes=local_target.stat().st_size,
                                sha256=hashlib.sha256(local_target.read_bytes()).hexdigest(),
                                created_at=datetime.now(timezone.utc).isoformat(),
                                source_type="interaction_file",
                            )
                        )
                    elif hasattr(item, "data"):
                        record = self.save_file(file_name, item.data, source_type="interaction_file")
                        saved_files.append(record)
                except Exception as err:
                    logger.warning("Failed capturing remote file %s: %s", item, err)

        # 2. Extract deliverables embedded in output text
        text_to_scan = output_text if output_text is not None else getattr(interaction, "output_text", "")
        if isinstance(text_to_scan, str) and text_to_scan.strip():
            extracted = self.extract_and_save_deliverables(text_to_scan)
            saved_files.extend(extracted)

        return saved_files

    def _update_manifest(self, record: SavedFile) -> None:
        """Appends the file record to the local manifest index."""
        manifest: Dict[str, Any] = {}
        if self.manifest_file.exists():
            try:
                with open(self.manifest_file, "r", encoding="utf-8") as f:
                    manifest = json.load(f)
            except Exception:
                manifest = {}

        manifest[record.file_name] = record.to_dict()
        with open(self.manifest_file, "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2)

    def list_saved_files(self) -> List[Dict[str, Any]]:
        """Returns all registered files in the local storage manifest."""
        if not self.manifest_file.exists():
            return []
        try:
            with open(self.manifest_file, "r", encoding="utf-8") as f:
                data = json.load(f)
                return list(data.values())
        except Exception:
            return []
